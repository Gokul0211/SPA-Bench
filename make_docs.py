#!/usr/bin/env python3
"""
Regenerate the documentation that is derived from manifest.json:

  README.md            the blocks between <!-- BEGIN generated:NAME --> and <!-- END generated:NAME -->
  docs/TEST_CASES.md   every ground-truth endpoint and asset, per app

Usage:
  python make_docs.py           rewrite
  python make_docs.py --check   exit 1 if any generated text is stale
"""

import argparse
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))


def load():
    with open(os.path.join(ROOT, 'manifest.json'), encoding='utf-8') as f:
        return json.load(f)


def blocks(m):
    s = m['summary']
    apps = ['| App | Emulates | Host port | Source maps | Login | Endpoints | of which test cases | Distinct paths | Assets |',
            '|---|---|---|---|---|---|---|---|---|']
    for a in m['apps']:
        paths = {e['url'].split('#')[0] if e['kind'] != 'graphql' else e['url'] for e in a['endpoints']}
        paths = {re.sub(r'\{[^}]+\}', '{}', p) for p in paths}
        apps.append(f"| {a['id']} | {a['framework']} {a['framework_version']}, {a['build_tool']} | {a['port']} | "
                    f"{'served' if a['source_maps_exposed'] else 'blocked (404)'} | {a['auth_method']} | {a['endpoint_count']} | "
                    f"{a['test_case_count']} | {len(paths)} | {len(a['assets'])} |")
    apps.append(f"| **total** | | | | | **{s['endpoints']}** | **{s['test_cases']}** | **{s['distinct_paths']}** | **{s['assets']}** |")

    classes = ['| Discovery class | Endpoints | Meaning |', '|---|---|---|']
    meaning = {
        'html_literal': 'path is written in the served HTML',
        'bundle_literal': 'every literal piece of the path is inside one string literal of a served bundle',
        'bundle_composed': 'assembled in a served bundle from several literals/variables (needs value-flow)',
        'sourcemap_literal': 'literal only in the TypeScript sources shipped in a source map',
        'sourcemap_composed': 'composed, and only in source-map sources',
        'runtime_data': 'the last piece comes from data fetched at runtime (WSDL operations)',
        'graphql_client_operation': 'GraphQL operation named in a client query',
        'graphql_sourcemap_operation': 'GraphQL operation named only in source-map sources',
        'graphql_introspection_only': 'GraphQL operation named nowhere in the client; schema introspection only',
        'probe_only': 'referenced by no client code; found only by probing well-known paths',
    }
    for c, n in s['by_discovery_class'].items():
        classes.append(f'| `{c}` | {n} | {meaning.get(c, "")} |')

    totals = (f"{s['endpoints']} endpoints ({s['test_cases']} hand-designed test cases + "
              f"{s['endpoints'] - s['test_cases']} further client calls), {s['distinct_paths']} distinct paths, "
              f"{s['assets']} assets, across {s['apps']} apps. {s['auth_required']} endpoints require login; "
              f"by kind: " + ', '.join(f'{v} {k}' for k, v in s['by_kind'].items()) + '.')
    return {'apps': '\n'.join(apps), 'classes': '\n'.join(classes), 'totals': totals}


def test_cases_md(m):
    out = ['# SPABench ground truth — every endpoint',
           '',
           f"Generated by `make_docs.py` from `manifest.json` v{m['version']}. Do not edit.",
           '',
           '`test case` = one of the hand-designed technique cases; the other rows are the rest of the API surface the',
           'client references. *Class* is derived from the served artifacts by `build_manifest.py`; *present in* lists',
           'every artifact the endpoint can be recovered from.', '']
    for a in m['apps']:
        out += [f"## {a['id']} — {a['name']}", '', a['description'], '',
                '| ID | Method | URL | Test case | Design technique | Class | Present in | Login |',
                '|---|---|---|---|---|---|---|---|']
        for e in a['endpoints']:
            out.append(f"| {e['id']} | {e['method']} | `{e['url']}` | {'yes' if e['test_case'] else ''} | "
                       f"{e.get('design_technique', '')} | {e['discovery_class']} | {', '.join(e['present_in'])} | "
                       f"{e['auth_method'] if e['auth_required'] else 'no'} |")
        if a['assets']:
            out += ['', '**Assets**', '', '| ID | URL | Design technique |', '|---|---|---|']
            out += [f"| {x['id']} | `{x['url']}` | {x['design_technique']} |" for x in a['assets']]
        out.append('')
    return '\n'.join(out) + '\n'


def render_readme(text, gen):
    for name, body in gen.items():
        pat = re.compile(rf'(<!-- BEGIN generated:{name} -->\n)(?:.*?\n)?(<!-- END generated:{name} -->)', re.S)
        if not pat.search(text):
            raise SystemExit(f'README.md has no generated:{name} block')
        text = pat.sub(lambda mm: mm.group(1) + body + '\n' + mm.group(2), text)
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    m = load()
    readme_p = os.path.join(ROOT, 'README.md')
    tc_p = os.path.join(ROOT, 'docs', 'TEST_CASES.md')
    readme_old = open(readme_p, encoding='utf-8').read()
    readme_new = render_readme(readme_old, blocks(m))
    tc_old = open(tc_p, encoding='utf-8').read() if os.path.exists(tc_p) else ''
    tc_new = test_cases_md(m)
    stale = [p for p, o, n in ((readme_p, readme_old, readme_new), (tc_p, tc_old, tc_new)) if o != n]
    if args.check:
        for p in stale:
            print('STALE', os.path.relpath(p, ROOT))
        print('docs up to date' if not stale else 'run python make_docs.py')
        return 1 if stale else 0
    for p, n in ((readme_p, readme_new), (tc_p, tc_new)):
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(n)
    print('updated', ', '.join(os.path.relpath(p, ROOT) for p in stale) or 'nothing (already up to date)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
